# Partikel-KI Voice Orb

Eine kleine lokale Web-App mit einer Partikelkugel, die auf deine Stimme reagiert.

Funktionen:
- Lautstärke-abhängige Kugel-Expansion beim Sprechen
- Ladeanimation während der Verarbeitung
- Sprach-Erkennung mit Mikrofon
- Sprach-Ausgabe ohne sichtbare Textausgabe
- Einfache lokale KI-Antworten in Deutsch

So startest du die App lokal:

1. Repository herunterladen oder klonen.
2. In den Ordner wechseln.
3. Einen lokalen Webserver starten:
   - Windows: `run.bat`
   - macOS/Linux: `chmod +x run.sh && ./run.sh`
4. Browser öffnen: `http://localhost:8000/`
5. Auf die Kugel klicken, um das Mikrofon zu aktivieren.

Hinweis:
- Die Spracherkennung funktioniert am besten in Chrome oder Edge.
- Für die volle Funktion musst du der App den Mikrofonzugriff erlauben.
- Die Sprachantworten sind ein lokales Demo-System und können später mit einer echten KI-API erweitert werden.


